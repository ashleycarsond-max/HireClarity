/**
 * COMPANY REGISTRY — the monitored-company list the sync loop scrubs.
 *
 * A monitored company is a record:
 *
 *   { name, boards: [{ board: "greenhouse"|"ashby"|"lever"|"workable",
 *                      boardId: <token/subdomain/org> }], careerUrl? }
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * HOW TO ADD A COMPANY (keep it real, keep it verified)
 * ─────────────────────────────────────────────────────────────────────────────
 * 1. Confirm the company actually runs a board on one of the supported ATSes
 *    (their careers page will link to boards.greenhouse.io/<token>,
 *    jobs.ashbyhq.com/<org>, jobs.lever.co/<org> or apply.workable.com/<sub>).
 * 2. VERIFY THE ENDPOINT LIVE before adding — it must return HTTP 200 plus a
 *    non-empty job list:
 *      Greenhouse: https://boards-api.greenhouse.io/v1/boards/<token>/jobs
 *      Ashby:      https://api.ashbyhq.com/posting-api/job-board/<org>
 *      Lever:      https://api.lever.co/v0/postings/<org>?mode=json
 *      Workable:   https://apply.workable.com/api/v1/widget/accounts/<sub>/jobs
 *    (Workable currently returns HTTP 429 bot-challenge — see note below.)
 * 3. Add an entry to SEED_COMPANIES with the exact public company name (this
 *    name becomes the `company` field on ingested postings, which is what the
 *    identity/removal logic keys on).
 *
 * SCALED REGISTRY: since 2026-08-14 the seed list is generated by the
 * discovery pipeline (`bun run discover`, engine/discover.ts) — candidates
 * are verified live against each board API and only HTTP-200-with-jobs
 * companies are emitted to engine/verified-companies.ts and merged here
 * (deduped by normalized name; a company verified on a second ATS gets the
 * extra board appended). The original five seeds (Greenhouse, Notion,
 * HighLevel, Veo, Employ) remain in the merge so the registry never shrinks.
 * Re-run `bun run discover` to grow the registry; re-running the sync picks
 * the new companies up automatically. Full per-candidate hit/failure reports
 * land in engine/data/discovery-report-*.txt.
 *
 * WORKABLE STATUS (verified 2026-08-14): apply.workable.com serves a bot
 * challenge (HTTP 429, even for /robots.txt), so no Workable account can be
 * verified or seeded today. The client exists in boards.ts and returns the 429
 * as a structured error; auto-discovery still registers Workable companies
 * from user-tracked URLs, and each sync reports the per-board failure honestly.
 */

