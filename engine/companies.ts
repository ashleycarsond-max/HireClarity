/**
 * Merge verified companies with the legacy seeds: dedupe by normalized name,
 * append extra boards when a company verifies on a second ATS. Deterministic
 * (sorted by name) so the sync cursor stays stable across deploys.
 */
export function mergeSeedCompanies(verified: MonitoredCompany[]): MonitoredCompany[] {
  const byKey = new Map<string, MonitoredCompany>();
  const normKey = (name: string) => name.trim().toLowerCase();
  const add = (c: MonitoredCompany) => {
    const key = normKey(c.name);
    const existing = byKey.get(key);
    if (!existing) {
      byKey.set(key, { ...c, boards: [...c.boards] });
      return;
    }
    for (const b of c.boards) {
      if (!existing.boards.some((x) => x.board === b.board && x.boardId === b.boardId)) {
        existing.boards.push(b);
      }
    }
    if (c.careerUrl && !existing.careerUrl) existing.careerUrl = c.careerUrl;
  };
  for (const c of [...LEGACY_SEEDS, ...verified]) add(c);
  return [...byKey.values()].sort((a, b) => a.name.localeCompare(b.name));
}

/** Verified-live seed list (see header for the verification procedure). */
export const SEED_COMPANIES: MonitoredCompany[] = mergeSeedCompanies(VERIFIED_COMPANIES);

/** Hosts that are actually ATS board pages (not marketing sites). */
const BOARD_HOSTS: Record<string, BoardKind> = {
  "boards.greenhouse.io": "greenhouse",
  "job-boards.greenhouse.io": "greenhouse",
  "jobs.ashbyhq.com": "ashby",
  "jobs.lever.co": "lever",
  "apply.workable.com": "workable",
};

const LOOPBACK_HOSTS = new Set(["127.0.0.1", "localhost", "::1", "[::1]"]);

function isLoopbackUrl(url: string): boolean {
  try {
    const host = new URL(url).hostname.toLowerCase();
    return LOOPBACK_HOSTS.has(host) || host.endsWith(".localhost");
  } catch {
    return false;
  }
}

/**
 * Derive the board + boardId a posting URL belongs to, when it is hosted on a
 * board we can scrub. Returns null for non-board URLs (incl. loopback fixtures).
 *
 *   boards.greenhouse.io/{token}/jobs/{id}  → greenhouse/{token}
 *   jobs.ashbyhq.com/{org}/{uuid}           → ashby/{org}
 *   jobs.lever.co/{org}/{uuid}              → lever/{org}
 *   apply.workable.com/{sub}/p/{shortcode}  → workable/{sub}
 */
export function boardRefFromUrl(url: string): CompanyBoardRef | null {
  if (isLoopbackUrl(url)) return null;
  try {
    const u = new URL(url);
    const host = u.hostname.toLowerCase();
    const board = BOARD_HOSTS[host];
    if (!board) return null;
    const seg = u.pathname.split("/").filter(Boolean);
    const boardId = seg[0] ?? null;
    if (!boardId) return null;
    return { board, boardId: decodeURIComponent(boardId) };
  } catch {
    return null;
  }
}

/**
 * AUTO-DISCOVERY FROM EXISTING DATA — the registry is the seed list PLUS every
 * company we can derive from postings already in the store whose canonical URL
 * is hosted on a supported board (i.e. postings users have checked). New
 * companies are upserted/deduped by normalized name; a company found on a
 * second board gets the extra board appended. Pure function of the store —
 * nothing is persisted (the scheduling layer can persist later if needed).
 */
export async function buildRegistry(store: Store, records?: PostingRecord[]): Promise<MonitoredCompany[]> {
  const byKey = new Map<string, MonitoredCompany>();
  const normKey = (name: string) => name.trim().toLowerCase();

  for (const c of SEED_COMPANIES) {
    byKey.set(normKey(c.name), { ...c, boards: [...c.boards] });
  }

  for (const r of records ?? (await store.getAll())) {
    if (!r.canonicalUrl) continue;
    const ref = boardRefFromUrl(r.canonicalUrl);
    if (!ref) continue;
    const name = r.company?.trim() || ref.boardId;
    const key = normKey(name);
    const existing = byKey.get(key);
    if (existing) {
      if (!existing.boards.some((b) => b.board === ref.board && b.boardId === ref.boardId)) {
        existing.boards.push(ref);
      }
    } else {
      byKey.set(key, { name, boards: [ref] });
    }
  }

  return [...byKey.values()].sort((a, b) => a.name.localeCompare(b.name));
}
